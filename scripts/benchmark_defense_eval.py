REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "DeepFilterNet"))

SR = 48_000
HOP = 480          # 10 ms
N_FFT = 960        # FFT window
ERB_BANDS = 32
DF_BINS = 96
N_FFT_BINS = N_FFT // 2 + 1  # 481

ACCEPTANCE = {
    "stationary_dsnr_db":   5.0,   # ≥ 5 dB improvement
    "impulsive_attenuation": 20.0,  # ≥ 20 dB shock suppression
    "rtf_max":               1.0,   # RTF < 1.0 (real-time)
}


# ===========================================================================
# Utility metrics
# ===========================================================================

def si_sdr(ref: np.ndarray, est: np.ndarray) -> float:
    """Scale-Invariant Signal-to-Distortion Ratio (dB)."""
    ref = ref - ref.mean()
    est = est - est.mean()
    alpha = np.dot(ref, est) / (np.dot(ref, ref) + 1e-8)
    target = alpha * ref
    noise = est - target
    return float(10 * np.log10((np.sum(target**2) + 1e-8) /
                               (np.sum(noise**2) + 1e-8)))


def output_snr(clean: np.ndarray, noisy: np.ndarray, enhanced: np.ndarray) -> float:
    """
    ΔSNRout = SNR(clean, enhanced) - SNR(clean, noisy).
    Returns the SNR improvement in dB.
    """
    def snr(sig, ref):
        noise = sig - ref
        return 10 * np.log10((np.sum(ref**2) + 1e-8) / (np.sum(noise**2) + 1e-8))
    return snr(enhanced, clean) - snr(noisy, clean)


def stoi_score(clean: np.ndarray, enhanced: np.ndarray, sr: int = SR) -> float:
    """
    Compute STOI. Uses pystoi if available, else returns a proxy metric
    (correlation coefficient in 1/3 octave bands).
    """
    try:
        from pystoi import stoi
        return float(stoi(clean, enhanced, sr, extended=False))
    except ImportError:
        pass

    # Proxy: short-time correlation in overlapping frames
    frame_len = int(0.025 * sr)
    hop = int(0.010 * sr)
    min_len = min(len(clean), len(enhanced))
    clean, enhanced = clean[:min_len], enhanced[:min_len]
    corrs = []
    for start in range(0, min_len - frame_len, hop):
        c = clean[start:start+frame_len]
        e = enhanced[start:start+frame_len]
        if c.std() > 1e-6 and e.std() > 1e-6:
            corrs.append(float(np.corrcoef(c, e)[0, 1]))
    return float(np.mean(corrs)) if corrs else 0.0


def peak_attenuation_db(input_sig: np.ndarray, output_sig: np.ndarray,
                        impulse_ts: list[float]) -> float:
    """
    Measure peak attenuation at impulse timestamps.
    Returns mean attenuation in dB across all impulse events.
    """
    if not impulse_ts:
        return 0.0
    attens = []
    window = int(0.020 * SR)  # 20 ms around each impulse
    for ts in impulse_ts:
        sample = int(ts * SR)
        lo, hi = max(0, sample - window), min(len(input_sig), sample + window)
        in_peak  = np.max(np.abs(input_sig[lo:hi])) + 1e-8
        out_peak = np.max(np.abs(output_sig[lo:hi])) + 1e-8
        attens.append(20 * np.log10(in_peak / out_peak))
    return float(np.mean(attens))


def recovery_frames(output_sig: np.ndarray, impulse_ts: list[float],
                    clean_sig: np.ndarray) -> float:
    """
    Count frames until speech quality recovers (SI-SDR returns to within 3 dB
    of the clean reference) after each impulse.
    Returns mean recovery time in frames.
    """
    if not impulse_ts:
        return 0.0
    recoveries = []
    baseline_sisdr = si_sdr(clean_sig, output_sig)
    for ts in impulse_ts:
        start_samp = int(ts * SR)
        max_look = int(0.5 * SR)  # look up to 500 ms after blast
        for frame_idx in range(0, max_look // HOP):
            s = start_samp + frame_idx * HOP
            e = s + HOP
            if e > len(output_sig) or e > len(clean_sig):
                break
            frame_sisdr = si_sdr(clean_sig[s:e], output_sig[s:e])
            if frame_sisdr >= baseline_sisdr - 3.0:
                recoveries.append(frame_idx)
                break
        else:
            recoveries.append(max_look // HOP)
    return float(np.mean(recoveries)) if recoveries else 0.0


def speech_swallowing(enhanced: np.ndarray, clean: np.ndarray,
                      impulse_ts: list[float]) -> float:
    """
    Speech swallowing metric: energy ratio of enhanced vs clean in the 100 ms
    window immediately following each impulse.
    Values < 0.5 indicate significant speech muting.
    """
    if not impulse_ts:
        return 1.0
    ratios = []
    window = int(0.100 * SR)
    for ts in impulse_ts:
        start = int(ts * SR) + int(0.015 * SR)  # 15 ms after blast peak
        end = min(start + window, len(clean))
        if end <= start:
            continue
        c_energy = np.sum(clean[start:end]**2) + 1e-10
        e_energy = np.sum(enhanced[start:end]**2) + 1e-10
        ratios.append(min(e_energy / c_energy, 2.0))  # cap at 2×
    return float(np.mean(ratios)) if ratios else 1.0


