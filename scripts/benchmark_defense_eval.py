"""
benchmark_defense_eval.py
==========================
Phase 3 of the DeepFilterNet Defence Upgrade Experimental Roadmap.

Runs the tri-model comparative benchmark:
  Model A – DefenseDfNet (baseline config: impulse_limiter / adaptive_dsp OFF)
  Model B – DefenseDfNet (adaptive_dsp ON, impulse_limiter OFF)
  Model C – DefenseDfNet FULL (all defence modules ON — the proposed system)

The benchmark evaluates all three models against the standardised defence test
partition generated by generate_defense_dataset.py, covering:

  1. Stationary Noise    -> ΔSNRout (dB), SI-SDR gain, engine harmonic SNR
  2. Non-Stationary Noise-> STOI intelligibility, SI-SDR gain
  3. Impulsive Gunfire   -> Shock peak attenuation (dB), post-blast recovery
                           frames, speech-swallowing metric
  4. Computational       -> RTF, peak memory (MB), frame processing time (ms)

Outputs
-------
  results/benchmark_<timestamp>/
    comparison_table.md   – human-readable markdown table
    comparison_table.csv  – machine-readable CSV
    metrics_full.json     – complete per-file metrics
    benchmark_summary.txt – single-glance acceptance check

Usage
-----
  python scripts/benchmark_defense_eval.py \\
      --dataset_dir data/defense_dataset \\
      --out_dir     results/benchmark_latest
"""

