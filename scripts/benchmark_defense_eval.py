def load_wav(path: str) -> np.ndarray:
    try:
        import soundfile as sf
        data, _ = sf.read(path, dtype="float32")
        return data
    except ImportError:
        import wave, struct
        with wave.open(path, "r") as wf:
            frames = wf.readframes(wf.getnframes())
            data = np.frombuffer(frames, dtype=np.int16).astype(np.float32) / 32768.0
        return data


def load_metadata(dataset_dir: str) -> list[dict]:
    csv_path = os.path.join(dataset_dir, "metadata.csv")
    if not os.path.isfile(csv_path):
        raise FileNotFoundError(f"metadata.csv not found in {dataset_dir}. "
                                "Run generate_defense_dataset.py first.")
    rows = []
    with open(csv_path, "r", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            row["class_id"] = int(row["class_id"])
            row["snr_db"] = int(row["snr_db"])
            row["n_impulses"] = int(row["n_impulses"])
            row["impulse_timestamps"] = eval(row["impulse_timestamps"])  # list
            rows.append(row)
    return rows


