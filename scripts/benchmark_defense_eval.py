def main() -> None:
    parser = argparse.ArgumentParser(
        description="Tri-model comparative benchmark for DeepFilterNet Defence."
    )
    parser.add_argument(
        "--dataset_dir", default="data/defense_dataset",
        help="Path to dataset generated by generate_defense_dataset.py"
    )
    parser.add_argument(
        "--out_dir", default="results/benchmark_latest",
        help="Output directory for benchmark results"
    )
    args = parser.parse_args()
    run_benchmark(args.dataset_dir, args.out_dir)


if __name__ == "__main__":
    main()
