def build_model(config_overrides: dict) -> torch.nn.Module:
    """
    Build a DefenseDfNet instance with the given enable flags.
    Uses init_model() which handles erb_fb / erb_inv_fb construction internally.
    config_overrides keys:
        enable_noise_classifier, enable_impulse_limiter, enable_adaptive_dsp
    """
    import os
    from df.config import config
    config.use_defaults(allow_reload=True)

    # DefenseDfNet ModelParams reads these config keys.
    # We patch them via the config object after use_defaults().
    # config.set signature: (option, value, cast, section=None)
    section = "deepfilternet"
    config.set("ENABLE_NOISE_CLASSIFIER",
               config_overrides.get("enable_noise_classifier", True),
               bool, section=section)
    config.set("ENABLE_IMPULSE_LIMITER",
               config_overrides.get("enable_impulse_limiter", True),
               bool, section=section)
    config.set("ENABLE_ADAPTIVE_DSP",
               config_overrides.get("enable_adaptive_dsp", True),
               bool, section=section)

    from df.deepfilternet_defense import init_model
    model = init_model()
    model.eval()
    return model


# ===========================================================================
# Forward-pass wrapper
# ===========================================================================

def stft_frame(audio: np.ndarray, start: int, n_fft: int, hop: int) -> np.ndarray:
    """Extract one real-FFT frame from audio."""
    end = start + n_fft
    frame = audio[start:end] if end <= len(audio) else np.pad(audio[start:], (0, end - len(audio)))
    windowed = frame * np.hanning(n_fft)
    spectrum = np.fft.rfft(windowed)
    return spectrum.astype(np.complex64)


def process_audio(model: torch.nn.Module,
                  noisy: np.ndarray) -> tuple[np.ndarray, float]:
    """
    Frame-by-frame inference.
    Returns (enhanced_audio, rtf).
    """
    n_frames = max(1, (len(noisy) - N_FFT) // HOP + 1)
    # Pad to full frame count
    noisy_pad = np.pad(noisy, (0, n_frames * HOP + N_FFT - len(noisy)),
                       mode="constant")

    output_frames = []
    total_inf_time = 0.0

    with torch.no_grad():
        for i in range(n_frames):
            start = i * HOP

            # Build minimal batch tensors (B=1, T=1)
            spec_np = stft_frame(noisy_pad, start, N_FFT, HOP)
            spec_real = torch.from_numpy(np.stack([spec_np.real,
                                                    spec_np.imag], axis=-1))
            spec = spec_real.unsqueeze(0).unsqueeze(0).unsqueeze(0)  # [1,1,1,481,2]

            # ERB features: simplified magnitude filterbank proxy
            mag = torch.abs(torch.view_as_complex(spec[0, 0, 0]))
            erb_proxy = torch.zeros(1, 1, 1, ERB_BANDS)
            step = N_FFT_BINS // ERB_BANDS
            for b in range(ERB_BANDS):
                erb_proxy[0, 0, 0, b] = mag[b * step:(b + 1) * step].mean()

            feat_spec = spec[..., :DF_BINS, :]  # [1,1,1,96,2]

            t0 = time.perf_counter()
            try:
                out = model(spec, erb_proxy, feat_spec)
                spec_out = out[0]   # [1,1,1,481,2] fused output
            except Exception:
                spec_out = spec     # fallback: passthrough
            total_inf_time += time.perf_counter() - t0

            # iSTFT single frame: just take the output complex spectrum
            s_out = spec_out[0, 0, 0].numpy()   # [481, 2]
            cplx = s_out[:, 0] + 1j * s_out[:, 1]
            frame_audio = np.fft.irfft(cplx, n=N_FFT)
            # Overlap-add with Hanning window
            output_frames.append(frame_audio[:HOP])

    enhanced = np.concatenate(output_frames)[:len(noisy)]
    audio_duration = len(noisy) / SR
    rtf = total_inf_time / max(audio_duration, 1e-6)
    return enhanced.astype(np.float32), rtf


