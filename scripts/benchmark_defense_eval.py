MODEL_CONFIGS = {
    "Model_A_Baseline": {
        "enable_noise_classifier": False,
        "enable_impulse_limiter":  False,
        "enable_adaptive_dsp":     False,
        "label": "Model A – DFN3 Core Only (Baseline)",
    },
    "Model_B_Adapted": {
        "enable_noise_classifier": True,
        "enable_impulse_limiter":  False,
        "enable_adaptive_dsp":     True,
        "label": "Model B – DFN3 + Noise Classifier + Adaptive DSP",
    },
    "Model_C_Full": {
        "enable_noise_classifier": True,
        "enable_impulse_limiter":  True,
        "enable_adaptive_dsp":     True,
        "label": "Model C – FULL DefenseDfNet (Proposed)",
    },
}


def run_benchmark(dataset_dir: str, out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)

    print(f"\n{'='*68}")
    print(f"  DeepFilterNet Defence Benchmark – Tri-Model Comparison")
    print(f"  Dataset : {os.path.abspath(dataset_dir)}")
    print(f"  Output  : {os.path.abspath(out_dir)}")
    print(f"{'='*68}\n")

    meta = load_metadata(dataset_dir)
    print(f"  Loaded {len(meta)} clips from metadata.csv\n")

    all_results: dict[str, Any] = {}
    summary_rows = []   # for markdown table

    for model_key, cfg in MODEL_CONFIGS.items():
        print(f"{'-'*68}")
        print(f"  Building {cfg['label']} …")

        # Build model
        model = build_model(cfg)
        param_count = sum(p.numel() for p in model.parameters())
        print(f"  Parameters: {param_count:,}")

        # Per-class accumulators
        acc: dict[str, list] = defaultdict(list)

        # Memory tracking
        tracemalloc.start()

        for row in meta:
            noisy_path = row["noisy_path"]
            clean_path = row["clean_path"]
            class_id   = row["class_id"]
            imp_ts     = row["impulse_timestamps"]

            if not os.path.isfile(noisy_path) or not os.path.isfile(clean_path):
                continue

            noisy = load_wav(noisy_path)
            clean = load_wav(clean_path)

            enhanced, rtf = process_audio(model, noisy)

            # Align lengths (enhanced may differ by a few samples due to frame boundary)
            min_len = min(len(clean), len(noisy), len(enhanced))
            clean_a = clean[:min_len]
            noisy_a = noisy[:min_len]
            enhanced_a = enhanced[:min_len]

            # --- universal metrics ---
            dsnr  = output_snr(clean_a, noisy_a, enhanced_a)
            sisdr = si_sdr(clean_a, enhanced_a) - si_sdr(clean_a, noisy_a)

            acc["rtf"].append(rtf)
            acc["dsnr"].append(dsnr)
            acc["sisdr"].append(sisdr)

            # --- class-specific metrics ---
            if class_id == 0:   # Stationary
                acc["stat_dsnr"].append(dsnr)
                acc["stat_sisdr"].append(sisdr)

            elif class_id == 1:   # Non-stationary
                stoi = stoi_score(clean_a, enhanced_a)
                acc["nonstat_stoi"].append(stoi)
                acc["nonstat_sisdr"].append(sisdr)

            elif class_id == 2:   # Impulsive
                atten = peak_attenuation_db(noisy_a, enhanced_a, imp_ts)
                recov = recovery_frames(enhanced_a, imp_ts, clean_a)
                swallow = speech_swallowing(enhanced_a, clean_a, imp_ts)
                acc["imp_attenuation"].append(atten)
                acc["imp_recovery_frames"].append(recov)
                acc["imp_swallow"].append(swallow)

        peak_mem_mb, _ = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        peak_mem_mb /= (1024 ** 2)

        def avg(key):
            vals = acc.get(key, [])
            return round(float(np.mean(vals)), 3) if vals else float("nan")

        results = {
            "label":                   cfg["label"],
            "n_params":                param_count,
            "mean_rtf":                avg("rtf"),
            "mean_frame_ms":           round(avg("rtf") * 10.0, 2),
            "peak_mem_mb":             round(peak_mem_mb, 1),
            "stat_dsnr_db":            avg("stat_dsnr"),
            "stat_sisdr_gain_db":      avg("stat_sisdr"),
            "nonstat_stoi":            avg("nonstat_stoi"),
            "nonstat_sisdr_gain_db":   avg("nonstat_sisdr"),
            "imp_attenuation_db":      avg("imp_attenuation"),
            "imp_recovery_frames":     avg("imp_recovery_frames"),
            "imp_swallow_ratio":       avg("imp_swallow"),
            "clips_evaluated":         len(acc.get("rtf", [])),
        }

        all_results[model_key] = results
        summary_rows.append(results)

        print(f"\n  Results for {model_key}:")
        print(f"    RTF                  : {results['mean_rtf']:.3f}  "
              f"({'[OK] REAL-TIME' if results['mean_rtf'] < 1.0 else '[X] TOO SLOW'})")
        print(f"    Stationary ΔSNR      : {results['stat_dsnr_db']:.2f} dB")
        print(f"    Non-Stat STOI        : {results['nonstat_stoi']:.3f}")
        print(f"    Impulse Attenuation  : {results['imp_attenuation_db']:.2f} dB  "
              f"({'[OK]' if results['imp_attenuation_db'] >= 20 else '[X]'} ≥ 20 dB)")
        print(f"    Peak Memory          : {results['peak_mem_mb']:.1f} MB\n")

    # -- Write comparison table (Markdown) ---------------------------------
    md_path = os.path.join(out_dir, "comparison_table.md")
    _write_markdown_table(all_results, md_path)

    # -- Write comparison table (CSV) ---------------------------------------
    csv_path = os.path.join(out_dir, "comparison_table.csv")
    _write_csv_table(summary_rows, csv_path)

    # -- Write full metrics JSON --------------------------------------------
    json_path = os.path.join(out_dir, "metrics_full.json")
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(all_results, fh, indent=2, default=str)

    # -- Write summary / acceptance report ---------------------------------
    summary_path = os.path.join(out_dir, "benchmark_summary.txt")
    _write_summary(all_results, summary_path)

    print(f"\n{'='*68}")
    print(f"  Benchmark COMPLETE")
    print(f"  +-- {md_path}")
    print(f"  +-- {csv_path}")
    print(f"  +-- {json_path}")
    print(f"  +-- {summary_path}")
    print(f"{'='*68}\n")


