def _write_markdown_table(results: dict, path: str) -> None:
    lines = [
        "# DeepFilterNet Defence – Tri-Model Comparison\n",
        f"*Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n",
        "",
        "## Stationary Noise Performance",
        "",
        "| Model | ΔSNR (dB) | SI-SDR Gain (dB) |",
        "| :---- | --------: | ---------------: |",
    ]
    for key, r in results.items():
        lines.append(f"| {r['label']} | {r['stat_dsnr_db']:.2f} | "
                     f"{r['stat_sisdr_gain_db']:.2f} |")
    lines += [
        "",
        "## Non-Stationary Noise Performance",
        "",
        "| Model | STOI | SI-SDR Gain (dB) |",
        "| :---- | ---: | ---------------: |",
    ]
    for key, r in results.items():
        lines.append(f"| {r['label']} | {r['nonstat_stoi']:.3f} | "
                     f"{r['nonstat_sisdr_gain_db']:.2f} |")
    lines += [
        "",
        "## Impulsive (Gunfire / Artillery) Performance",
        "",
        "| Model | Peak Atten. (dB) | Recovery Frames | Swallow Ratio |",
        "| :---- | ---------------: | --------------: | ------------: |",
    ]
    for key, r in results.items():
        chk = "[OK]" if r["imp_attenuation_db"] >= 20 else "[X]"
        lines.append(f"| {r['label']} | {chk} {r['imp_attenuation_db']:.2f} | "
                     f"{r['imp_recovery_frames']:.1f} | {r['imp_swallow_ratio']:.3f} |")
    lines += [
        "",
        "## Computational Performance",
        "",
        "| Model | Params | RTF | Frame Time (ms) | Peak Mem (MB) |",
        "| :---- | -----: | --: | --------------: | ------------: |",
    ]
    for key, r in results.items():
        rtf_chk = "[OK]" if r["mean_rtf"] < 1.0 else "[X]"
        lines.append(f"| {r['label']} | {r['n_params']:,} | "
                     f"{rtf_chk} {r['mean_rtf']:.3f} | "
                     f"{r['mean_frame_ms']:.2f} | {r['peak_mem_mb']:.1f} |")

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def _write_csv_table(rows: list[dict], path: str) -> None:
    if not rows:
        return
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _write_summary(results: dict, path: str) -> None:
    lines = [
        "=" * 60,
        "  BENCHMARK ACCEPTANCE REPORT",
        f"  {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "=" * 60,
        "",
    ]
    for key, r in results.items():
        lines.append(f"  [{key}]  {r['label']}")
        lines.append(f"  {'-'*56}")

        stat_ok = r["stat_dsnr_db"] >= ACCEPTANCE["stationary_dsnr_db"]
        imp_ok  = r["imp_attenuation_db"] >= ACCEPTANCE["impulsive_attenuation"]
        rtf_ok  = r["mean_rtf"] < ACCEPTANCE["rtf_max"]

        lines.append(f"  Stationary ΔSNR ≥ {ACCEPTANCE['stationary_dsnr_db']} dB : "
                     f"{'PASS [OK]' if stat_ok else 'FAIL [X]'}  "
                     f"({r['stat_dsnr_db']:.2f} dB)")
        lines.append(f"  Impulse atten. ≥ {ACCEPTANCE['impulsive_attenuation']} dB : "
                     f"{'PASS [OK]' if imp_ok else 'FAIL [X]'}  "
                     f"({r['imp_attenuation_db']:.2f} dB)")
        lines.append(f"  RTF < {ACCEPTANCE['rtf_max']}                   : "
                     f"{'PASS [OK]' if rtf_ok else 'FAIL [X]'}  "
                     f"({r['mean_rtf']:.3f})")

        overall = "ALL PASS [OK]" if (stat_ok and imp_ok and rtf_ok) else "NEEDS REVIEW [X]"
        lines.append(f"  Overall: {overall}")
        lines.append("")

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("".join(f"\n{l}" for l in lines))


